	<h2>Vos devoirs de roleplay</h2>

	<p>Vous aimez visualiser le décor autour de vous, et les PNJ qui sont dedans ? C’est certainement pareil pour votre MJ. Il aime certainement bien visualiser ce que font les PJ et comment ils se comportent. 😁</p>

	<!-- Conseils de roleplay -->
	<details>
		<summary>
			<h3>Conseils de roleplay</h3>
		</summary>

		<p>Mais qu’entends-je donc là par roleplay ? Pas une longue tirade qui ralentit le scénar pour parler des confitures de tati Morgane (quoique, de temps en temps et si c’est rigolo…).</p>

		<ul class="flow pl-1">
			<li><b>Décrire ce que fait votre personnage</b>, de manière à ce que tout le monde le visualise.</li>

			<li><b>Parler en style direct</b> (oubliez les « je lui dis que… »).</li>

			<li><b>Ne pas parler en terme de jeu</b> (« je ne peux pas, j’ai 7 en <i>Escalade</i> ! »)</li>

			<li><b>Agir de manière à avoir une réponse</b>, plutôt que de poser une question directe (ex. « il est profond le trou ? » vs « je m’approche du gouffre et j’essaie de voir le fond »).</li>

			<li><b>Tirer parti de chaque élément de son personnage</b> pour ajouter une touche de réalisme et de profondeur à la scène : son caractère certes, mais aussi ce qu’il porte, son équipement, son état…</li>

			<li><b>Interagir entre PJ</b> et pas seulement entre joueurs.</li>
		</ul>
	</details>

	<p>Pour ça, bien sûr, il faut <b>connaître son personnage sur le bout des doigts</b>. Alors, je ne dis pas que c’est toujours possible, ni même souhaitable. Mais quand on est dans une scène immersive du scénario, une touche de roleplay rend la partie encore plus sympa pour tout le monde, y compris le MJ.</p>

	<hr>

	<p>Engagement à s’impliquer activement dans le récit et les mécanismes de jeu, en évitant les comportements perturbateurs ou hors sujet. Cet engagement revêt plusieurs dimensions : cognitive (attention portée au jeu), créative (contribution à la fiction), émotionnelle (investissement dans les personnages et les situations) et sociale (participation aux dynamiques de groupe). Le niveau d’engagement attendu peut varier considérablement selon les groupes et doit idéalement faire l’objet d’une entente explicite. Certains groupes privilégient une approche décontractée autorisant les digressions, tandis que d’autres recherchent une immersion soutenue exigeant une concentration constante.</p>

	<p>Les joueurs s’efforcent de créer un personnage qui s’aligne sur le thème, le ton et les objectifs de la campagne, enrichissant ainsi l’expérience collective. Cette dimension du contrat social touche à l’esthétique du jeu et aux conventions narratives adoptées par le groupe. Elle suppose une compréhension partagée du genre exploré, des codes narratifs appropriés et des limites thématiques acceptables. La production de contenu conforme ne signifie pas l’uniformité créative, mais plutôt une harmonisation des contributions individuelles au service d’une vision cohérente de l’univers fictif partagé.</p>

	<p>Savoir quand on peut avoir un moment de rigolade et quand ça nuit à l’ambiance</p>

