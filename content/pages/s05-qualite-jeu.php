	<h2>Pacte de le table</h2>

	<p class="italic ta-center" style="margin-top: -.5em">Nos engagements pour des parties vivantes</p>

	<p>Après des années de pratique, nous savons tous comment fonctionne une partie de jeu de rôle. Mais, entre la fatigue, les soucis extérieurs et les habitudes prises au fil du temps, il est facile de glisser vers un jeu « en pilotage automatique ».</p>

	<!-- Le contrat -->
	<details>
		<summary>
			<h3>Le contrat</h3>
		</summary>
		<p>Une bonne partie n’est pas un spectacle où le meneur de jeu fait la démonstration de son histoire devant des spectateurs. C’est un contrat tacite, une création commune : </p>

		<ul class="flow pl-1">
			<li><b>L’engagement du MJ :</b> préparer un cadre solide, poser le décor, donner vie à l’adversité, arbitrer en toute impartialité et respecter vos choix.</li>

			<li><b>L’engagement des joueurs :</b> injecter l’énergie, le rythme et la couleur qui font qu’une scène devient mémorable.</li>
		</ul>

		<p>Pour que nos soirées soient plus immersives, plus vivantes et plus rythmées, voici les engagements que je vous propose de placer au cœur de notre table.</p>
	</details>

	<!-- 1. Être le MJ de votre perso -->
	<details>
		<summary>
			<h3>1. Être le « MJ » de votre personnage</h3>
		</summary>

		<p><b>C’est la clé de voûte.</b> Tout le travail d’immersion ne peut pas reposer uniquement sur les épaules du MJ. Si vous vous contentez d’annoncer des compétences ou de réagir mollement à ses descriptions, la partie perd immédiatement de sa saveur.</p>

		<ul class="flow pl-1">
			<li><b>Décrire ce que vous faites :</b> donnez à voir. Au lieu de dire « <i>J’attaque le garde</i> », décrivez le geste : votre prise d’élan, votre hargne, le coup de bouclier pour le déséquilibrer… Donnez de la matière aux autres pour qu’ils visualisent la scène.</li>

			<li><b>Exploiter l’allure et l’équipement :</b> ne laissez pas votre fiche dormir. Utilisez ce que porte votre personnage pour enrichir vos descriptions : ajuster une sangle, s'essuyer le front avec une manche crasseuse, faire grincer une botte, tirer une bouffée de pipe avant de répondre. Ce sont ces détails concrets qui donnent du poids à une scène.</li>

			<li><b>Agir plutôt que de poser des questions techniques :</b> ne demandez pas « <i>Le trou est profond ?</i> » ou « <i>Est-ce que le garde a l’air attentif ?</i> ». Dites plutôt : « <i>Je m’approche du gouffre et j’essaie de voir le fond</i> » ou « <i>Je m’adosse au comptoir et j’observe discrètement les mouvements du garde</i> ».</li>

			<li><b>Penser « monde réel », pas « jeu vidéo » :</b> bannissez les chiffres et le jargon à l’oral (les points de vie, les malus, le méta-jeu). Évitez les réflexes de jeu vidéo comme chercher à « trouver l’indice » même de manière absurde ou dire « <i>C’est mort, j’ai 7 en Escalade</i> ». Dites plutôt : « Je ne vais jamais y arriver, la paroi est trop lisse ».</li>

			<li><b>Parler en direct et jouer entre vous :</b> « <i>Je te préviens, si tu touches à cette porte, on est morts</i> », C’est mieux que « <i>Je lui dis de ne pas ouvrir la porte</i> ». Surtout, <b>interagissez entre vous</b>. Ne vous adressez pas uniquement au MJ : complotez ensemble, discutez au coin du feu, confrontez vos points de vue. Une table où les personnages se parlent réellement est une table qui vit.</li>
		</ul>
	</details>

	<!-- 2. Être acteur de l’histoire -->
	<details>
		<summary>
			<h3>2. Être acteur de l’histoire</h3>
		</summary>

		<p>Rien n’est plus usant pour un meneur que de devoir « tirer les vers du nez » des joueurs ou de pousser artificiellement le groupe en avant à chaque scène.</p>

		<ul class="flow pl-1">

			<li><b>Respecter le ton de l'univers et de la campagne :</b> que ce soit à la création du personnage ou dans ses répliques, respectez les codes de l'histoire. Éviter les concepts anachroniques, absurdes ou en décalage complet avec le groupe. L'originalité fonctionne quand elle sert l'atmosphère, pas quand elle est en décalage complet avec l’ambiance.</li>

			<li><b>S’engager activement face aux événements :</b> il est parfaitement légitime d’incarner un personnage prudent, méfiant ou calculateur, qui ne fonce pas tête baissée dans le premier piège venu. Mais cette prudence doit se traduire par de l’action : espionner, tendre un piège, chercher une route alternative, interroger un témoin. La méfiance doit être un moteur d’enquête ou de préparation, jamais une excuse pour l’inaction ou pour attendre que les événements se résolvent d’eux-mêmes.</li>

			<li><b>Prendre des initiatives :</b> fixez-vous des objectifs personnels ou d’équipe. N’attendez pas que le monde vienne frapper à votre porte : provoquez les rencontres, fouillez, exploitez vos contacts, tentez des approches inattendues.</li>

			<li><b>Avancer en groupe :</b> même si vos personnages ont des désaccords ou des personnalités bien trempées, gardez à l’esprit qu’on joue ensemble. Les individualités fortes enrichissent le groupe, mais elles ne doivent jamais bloquer l’aventure ou paralyser la table.</li>
		</ul>
	</details>

	<!-- 3. Préserver le rythme et l’ambiance -->
	<details>
		<summary>
			<h3>3. Préserver le rythme et l’ambiance</h3>
		</summary>

		<p>Dans le feu de l’action, votre MJ annonce des difficultés, des modificateurs ou des conséquences. Pour que la tension dramatique fonctionne, la fluidité de la partie doit primer sur la contestation.</p>

		<ul class="flow pl-1">
			<li><b>Ne pas marchander les décisions :</b> contester un malus, négocier pour gratter un point ou discuter une issue casse immédiatement l’ambiance et ralentit la partie pour tout le monde. Une mauvaise passe, une difficulté imprévue ou un échec cuisant ne sont pas négatifs : ce sont des opportunités de jeu qui rendent l’histoire intéressante.</li>

			<li><b>La règle de l’oubli objectif :</b> il arrive à votre MJ d’oublier un élément concret de la situation (par exemple : « <i>N’oublie pas que j’avais allumé une torche au tour précédent</i> » ou « <i>Mon personnage a bu sa potion de force il y a cinq minutes</i> »). Dans ce cas, le rappeler au MJ est parfaitement légitime. En revanche, une fois les faits posés, son appréciation de l’application des règles ne doit plus faire l’objet de débats en cours de partie.</li>

			<li><b>Savoir lire la scène (humour vs tension) :</b> les éclats de rire et la détente sont <b>essentiels</b>. Mais il faut savoir sentir l'atmosphère d'une scène : une vanne hors-jeu ou une digression au milieu d'un moment dramatique, d'une négociation tendue ou d'une scène d'angoisse brise instantanément l'immersion qu’on s’efforce de construire.</li>
		</ul>
	</details>

	<!-- 4. La maîtrise technique de notre outil -->
	<details>
		<summary>
			<h3>4. Maîtrise technique : l’outil et la fiche</h3>
		</summary>

		<p>Nous jouons à distance via une application maison. Elle est complète, parfois dense, et son interface a ses limites, que je m’efforce d’améliorer continûment.</p>

		<p>Chacun s’engage, en dehors des séances, à prendre le temps de se familiariser avec l'outil et à <b>connaître son personnage sur le bout des doigts</b> (ses capacités, ses désavantages, son équipement, ses sorts). Hésiter dix minutes sur un point de règle personnel ou chercher un bouton en plein combat casse la dynamique.</p>
	</details>
