	<h2>Densifier vos parties</h2>

	<p>Rendez vos parties plus intenses. Source : chaîne Youtube <a href="https://www.youtube.com/watch?v=hsb3uKvXtj8">Lestat JdR</a></p>

	<!-- Qu’est-ce que la densité d’une partie ? -->
	<details>
		<summary>
			<h3>Qu’est-ce que la densité d’une partie ?</h3>
		</summary>

		<p>La densité est définie comme le ratio entre le nombre de scènes ou situations marquantes et la durée totale de la partie. Un scénario dense multiplie les blocs identifiables où les joueurs doivent prendre des décisions impactantes.</p>
	</details>

	<!-- Le contenu avant la durée -->
	<details>
		<summary>
			<h3>Le contenu avant la durée</h3>
		</summary>

		<p>Le piège courant pour beaucoup de maîtres du jeu est de vouloir atteindre une durée fixe en étirant inutilement des scènes ou des introductions.</p>

		<ul class="flow pl-1">
			<li><b>Ne forcez pas la durée :</b> mieux vaut un scénario court et intense qu’un scénario artificiellement allongé.</li>
			<li><b>Le test <i>a posteriori</i> :</b> si vous avez du mal à raconter ce qui s’est passé en citant plusieurs étapes clés, c’est que le scénario manque de densité.</li>
		</ul>
	</details>

	<!-- Outils pour densifier vos parties -->
	<details>
		<summary>
			<h3>Outils pour densifier vos parties</h3>
		</summary>

		<ul class="flow pl-1">
			<li><b>Se projeter :</b> visualisez votre scénario en accéléré et vérifiez si chaque bloc contient une décision réelle pour les joueurs.</li>
			<li><b>Le pouvoir de l’ellipse :</b> le MJ est le garant du rythme. N’hésitez pas à couper les temps morts pour passer à la situation suivante dès que le potentiel d’une scène est épuisé.</li>
			<li><b>Synthèse en jeu :</b> si les joueurs tournent en rond, résumez leurs idées pour les pousser à prendre une décision et faire avancer l’action.</li>
		</ul>
	</details>

	<!-- Rythme lent vs Mauvais rythme -->
	<details>
		<summary>
			<h3>Rythme lent vs Mauvais rythme</h3>
		</summary>

		<p>Il existe une différence entre un rythme lent positif (basé sur le contenu émotionnel ou psychologique, tout en restant dense en situations) et un rythme lent négatif (qui résulte simplement d’un manque de densité et d’un manque de progression).</p>
	</details>

