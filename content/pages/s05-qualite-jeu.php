		<h4>Les modificateurs physiologiques</h4>
		<ul class="flow pl-1">
			<li><b>Résonance (placement) :</b> <i>Nasal</i> (voix coincée dans le nez, agaçant ou pédant) vs <i>Guttural</i> (coincé au fond de la gorge/poitrine) vs <i>Neutre</i>.</li>
			<li><b>Friction :</b> <i>Soufflé</i> (voilé, beaucoup d’air résiduel, mystérieux ou faible) vs <i>Sec</i> (cordes serrées, claquant, net).</li>
			<li><b>Âge :</b> <i>Enfant</i> (énergie vive, intonation montante, larynx haut) / <i>Adulte</i> / <i>Vieillard</i> (vitesse réduite, pauses articulatoires, fragilité du souffle).</li>
			<li><b>Gabarit perçu :</b> <i>Petit</i> (larynx haut, résonance aiguë) vs <i>Grand</i> (larynx bas, résonance caverneuse).</li>
			<li><b>Débit et Volume :</b> Rapide / Lent ; Murmuré / Modéré / Projeté.</li>
		</ul>

		<h4>L’attitude</h4>
		<ul class="flow pl-1">
			<li><b>Amical :</b> intonations montantes en fin de phrase, bienveillance, voix accueillante.</li>
			<li><b>Impartial :</b> ligne mélodique plate, ton monocorde, neutralité administrative ou froideur professionnelle.</li>
			<li><b>Agressif :</b> attaque dure sur les consonnes, projection sèche, ton descendant et tranchant.</li>
		</ul>

		<h4>Altérations optionnelles et accents</h4>
		<ul class="flow pl-1">
			<li><b>Défauts d’élocution :</b> un léger zézaiement (zozotement), un chuintement, un problème pour rouler les « R » (rhotacisme) ou le parler fort et monotone d’une personne malentendante suffisent à rendre un PNJ inoubliable.</li>
			<li><b>Accents :</b> à utiliser avec parcimonie. Un accent approximatif ou trop forcé distrait les joueurs et devient vite fatigant sur la durée. Privilégiez les variations de débit, d’attitude et de résonance.</li>
		</ul>
	</details>

	<!-- Parole de PNJ -->
	<details>
		<summary>
			<h3>3. Parole de PNJ : au-delà du son</h3>
		</summary>

		<p>La voix n’est que le conteneur ; l’impact dépend de la manière dont le discours est distribué aux joueurs.</p>

		<h4>L’art de la rétention (« Tease, don’t tell »)</h4>

		<p>Un PNJ ne doit jamais réciter un bloc d’exposition d’un seul trait. Donnez l’information par parcelles incomplètes : une bribe de phrase, une allusion voilée, un détail troublant. Forcez les joueurs à poser des questions pour tirer les vers du nez du personnage. La valeur d’une information dépend de l’effort fourni pour l’obtenir.</p>

		<h4>Le pouvoir du silence</h4>

		<p>Le silence est un outil de mise en scène sous-estimé :</p>
		<ul class="flow pl-1">
			<li><b>Le silence d’autorité :</b> soutenir le regard d’un joueur 3 secondes avant de répondre démontre une domination totale.</li>
			<li><b>Le silence d’embarras :</b> marquer une rupture en pleine phrase signale un secret ou une hésitation bien mieux que de longs discours.</li>
			<li><b>Le vide à combler :</b> se taire pousse naturellement les joueurs à meubler le silence, révélant souvent leurs propres plans ou faiblesses.</li>
		</ul>

		<h4>Tics de langage et syntaxe</h4>

		<p>Une signature verbale repose souvent sur un gimmick syntaxique léger :</p>
		<ul class="flow pl-1">
			<li><b>Mots récurrents :</b> un adverbe obsessionnel (<i>« Techniquement »</i>, <i>« Manifestement »</i>), un juron local ou un tic de ponctuation verbale (<i>« pas vrai ? »</i>, <i>« voyons… »</i>).</li>
			<li><b>Structure de phrase :</b> phrases très courtes et sans fioritures (militaire, pragmatique) vs subordonnées à rallonge avec hésitations (érudit pédant, avocat, courtisan, menteur qui improvise).</li>
		</ul>

		<h4>La règle de consistance</h4>

		<p>Une fois qu’un profil est attribué à un PNJ, notez-le sous forme de tag condensé dans vos fiches :</p>
		<p><code>[Presser | Guttural + Sec | Lent / Faible | But : Intimider]</code></p>
		<p>Changer arbitrairement de voix ou d’attitude en cours de jeu brise l’illusion et crée une confusion immédiate autour de la table. La fidélité au profil choisi prime toujours sur la complexité de l’interprétation.</p>
	</details>
</article>

