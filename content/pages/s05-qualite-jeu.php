	<h2>Les PNJ ont la parole</h2>

	<p>Inutile d’être un imitateur professionnel pour donner vie à ses PNJ. Une interprétation efficace repose sur trois éléments : calibrer la posture en amont, appliquer des filtres vocaux simples et structurés, et maîtriser la dynamique de l’échange.</p>

	<!-- Concevoir le PNJ -->
	<details>
		<summary>
			<h3>1. En amont du dialogue</h3>
		</summary>

		<p>Avant de faire parler un PNJ, trois éléments préparatoires conditionnent l’échange.</p>

		<h4>L’intention (le but de l’interaction)</h4>

		<p>Chaque dialogue est un rapport de force orienté par un objectif précis. Un PNJ parle rarement dans le vide. Il cherche à :</p>

		<ul class="flow pl-1">
			<li><b>Obtenir :</b> séduire, quémander, négocier, soutirer une information.</li>
			<li><b>Repousser :</b> intimider, expédier l’échange, marquer son autorité.</li>
			<li><b>Dissimuler :</b> noyer le poisson, détourner l’attention, mentir.</li>
		</ul>

		<h4>L’ancrage corporel</h4>

		<p>La posture modifie mécaniquement la colonne d’air et offre un repère visuel immédiat aux joueurs :</p>

		<ul class="flow pl-1">
			<li><b>Le buste :</b> se tenir droit et rigide (autorité, fierté, formation militaire) ou affaissé et penché en avant (fatigue, soumission, conspiration).</li>
			<li><b>Le menton :</b> relevé (condescendance, larynx étiré vers le haut) ou rentré vers la poitrine (méfiance, voix plus sourde).</li>
			<li><b>Le regard :</b> fixer intensément un joueur ou balayer la pièce sans jamais croiser les yeux de la table.</li>
			<!-- <li><b>Astuce mécanique pour le tremblement :</b> pour simuler la terreur, le froid ou une grande faiblesse, contractez fermement les pectoraux et les avant-bras contre votre torse : la voix tremblera naturellement.</li> -->
		</ul>

		<h4>La phrase déclencheuse</h4>

		<p>Pour retrouver instantanément l’attitude et le placement d’un PNJ récurrent, associez-lui une courte réplique étalon. Prononcée mentalement avant de prendre la parole, elle sert de déclencheur neuromusculaire (ex. : <i>« Encore vous ? »</i>, <i>« Patience, mon enfant… »</i>, <i>« Circulez, y’a rien à voir. »</i>, <i>« Qu’est-ce qu’on lui veut, au vieux ? »</i>, <i>« Bien le bonjour, messires. »</i>).</p>

	</details>

	<!-- Donner de la voix -->
	<details>
		<summary>
			<h3>2. La matrice vocale</h3>
		</summary>

		<p>Pour varier les voix de façon systématique, on utilise la méthode des actions physiques de <i>Rudolf Laban</i>, croisée avec quelques modificateurs acoustiques (voir cette <a href="https://www.youtube.com/watch?v=FVmAEezr6ao">vidéo</a>).</p>

		<h4>Les 3 axes</h4>

		<p>Le timbre de base est déterminé par trois polarités physiques :</p>

		<!-- Le poids -->
		<details class="border p-½">
			<summary>
				<h5>1. Le Poids</h5>
			</summary>

			<p><b>Inertie et impact.</b> Cet axe quantifie la <b>résistance</b> et la <b>masse</b> perçue derrière chaque son. Ce n’est pas le volume sonore (on peut parler fort et être léger, ou chuchoter avec un poids écrasant).</p>

			<ul class="flow pl-1">
				<li><b>Léger : faible inertie, délicatesse, apesanteur</b><br>
					<ul>
						<li><i>Mécanique vocale :</i> faible fermeture glottique, articulation du bout des lèvres, peu d’engagement des muscles abdominaux/du tronc. La voix effleure l’espace.</li>
						<li><i>Ce que les joueurs perçoivent :</i> quelqu’un qui ne s’impose pas physiquement, qui esquive, ou qui est détaché des contingences matérielles.</li>
						<li><i>Analogie physique :</i> poser délicatement une feuille de papier, souffler sur un pissenlit.</li>
					</ul>
				</li>
				<li>
					<b>Lourd : forte inertie, densité, impact</b><br>
					<ul>
						<li><i>Mécanique vocale :</i> pression sous-glottique élevée, mâchoire et diaphragme ancrés. Chaque mot « tombe » avec une masse physique, il y a de l’impact dans les consonnes.</li>
						<li><i>Ce que les joueurs perçoivent :</i> l’autorité, l’inflexibilité, la fatigue écrasante ou la menace physique. Les mots pèsent sur l’interlocuteur.</li>
						<li><i>Analogie physique :</i> frapper une enclume avec un marteau, enfoncer une porte d’épaule.</li>
					</ul>
				</li>
			</ul>
		</details>

		<!-- L’espace -->
		<details class="border p-½">
			<summary>
				<h5>2. L’Espace</h5>
			</summary>

			<p><b>Géométrie de l’attention.</b> Cet axe décrit la <b>trajectoire</b> et la <b>focalisation</b> de l’intention vers l’interlocuteur.</p>

			<ul class="flow pl-1">
				<li>
					<b>Direct : vecteur linéaire, ciblage laser.</b><br>
					<ul>
						<li><i>Mécanique vocale :</i> élocution ciblée sur un point précis (un joueur, une idée). Absence de détours mélodiques. La voix va tout droit, sans variations parasites, le regard est fixe.</li>
						<li><i>Ce que les joueurs perçoivent :</i> quelqu’un d’extrêmement focalisé, méthodique, honnête ou dangereux parce qu’il ne lâche rien.</li>
						<li><i>Analogie :</i> un rayon laser, pointer du doigt sans trembler.</li>
					</ul>
				</li>
				<li>
					<b>Indirect : diffusion, trajectoire brownienne.</b><br>
					<ul>
						<li><i>Mécanique vocale :</i> l’intonation varie, serpente, contourne le sujet. Le regard balaye la pièce, les intonations montent et descendent de manière imprévisible, les phrases semblent dériver.</li>
						<li><i>Ce que les joueurs perçoivent :</i> la distraction, la folie, la duplicité, l’ivresse ou l’hésitation. Le PNJ parle « à la pièce » ou « dans le vide » plutôt qu’à une cible précise.</li>
						<li><i>Analogie :</i> une lanterne qui éclaire large, une fumée qui se disperse.</li>
					</ul>
				</li>
			</ul>
		</details>

		<!-- Le temps -->
		<details class="border p-½">
			<summary>
				<h5>3. Le Temps</h5>
			</summary>

			<p><b>Élasticité et urgence.</b> Cet axe ne mesure pas simplement la vitesse brute d’élocution (le tempo), mais <b>l’attitude face à la durée</b>. Il s’agit du rapport entre l’accélération et la décélération : est-ce que le son explose en un instant (staccato) ou est-ce qu’il résiste à l’écoulement du temps (legato) ?</p>

			<ul class="flow pl-1">
				<li>
					<b>Soudain : l’impulsion, l’instantanéité, le haché.</b><br>
					<ul>
						<li><i>Mécanique vocale :</i> attaque glottique franche et arrêt net. Les voyelles sont raccourcies au strict minimum, les consonnes occlusives (T, K, P, B, D) claquent. Les mots sont projetés comme des paquets discrets sans liaison fluide entre eux.</li>
						<li><i>Ce que les joueurs perçoivent :</i> l’urgence, la nervosité, l’impatience, l’agressivité réflexe, ou l’efficacité chirurgicale d’un esprit qui n’a pas de temps à perdre. Le PNJ réagit à la milliseconde.</li>
						<li><i>Analogie physique :</i> une étincelle, un tir réflexe, une impulsion de Dirac (pic d’énergie instantané).</li>
					</ul>
				</li>
				<li>
					<b>Soutenu : la continuité, l’étirement, le flux lié.</b>
					<ul>
						<li><i>Mécanique vocale :</i> attaque progressive, voyelles prolongées et ouvertes. Le son ne s’arrête jamais brutalement ; les mots glissent les uns dans les autres via des liaisons douces. L’expiration est contrôlée pour maintenir une pression constante sans à-coups.</li>
						<li><i>Ce que les joueurs perçoivent :</i> le contrôle absolu, la contemplation, l’hypnose, la condescendance ou la léthargie. Le PNJ refuse d’être bousculé ; il impose son propre rapport au temps à la table.</li>
						<li><i>Analogie physique :</i> l’écoulement d’un fluide visqueux (comme du miel), l’étirement continu d’un élastique.</li>
					</ul>
				</li>
			</ul>
		</details>

