<article>
	<h2>L’ellipse</h2>

	<p>L’ellipse consiste à omettre volontairement une période de temps du récit pour accélérer le rythme de l’histoire et se concentrer sur les moments narrativement significatifs. Source : <a href="https://jeuxderole.org/ellipse-narrative-saut-temporel">jeuxderole.org</a></p>

	<!-- Caractéristiques principales -->
	<details>
		<summary>
			<h3>Caractéristiques principales</h3>
		</summary>
		<ul class="flow pl-1">
			<li><b>Délimitation temporelle claire :</b> le début et la fin de la période omise doivent être explicitement établis</li>
			<li><b>Conservation de la cohérence :</b> les événements avant et après l’ellipse doivent s’articuler logiquement</li>
			<li><b>Accord tacite ou explicite des joueurs :</b> les joueurs peuvent s’opposer à une ellipse s’ils le souhaitent.</li>
			<li><b>Gestion des conséquences :</b> les changements survenus pendant la période ellipsée doivent être établis et intégrés</li>
			<li><b>Préservation de la capacité d’action et de décision des joueurs :</b> leurs décisions concernant les actions de leurs personnages pendant la période omise doivent être prises en compte</li>
		</ul>
	</details>

	<!-- Points de vigilance -->
	<details>
		<summary>
			<h3>Points de vigilance</h3>
		</summary>

		<ul class="flow pl-1">
			<li><b>Immersion et efficacité narrative :</b> des ellipses trop fréquentes peuvent nuire à l’immersion</li>
			<li><b>Illusionisme :</b> l’ellipse ne doit pas être utilisée pour forcer certains développements narratifs sans tenir compte des choix des joueurs</li>
			<li><b>Gestion des développements « hors-champ » :</b> gérer ce qui se passe pendant l’ellipse sans tomber dans l’arbitraire</li>
			<li><b>L’impact sur le flow :</b> l’ellipse peut maintenir le rythme, mais peut aussi créer des ruptures dans l’engagement des joueurs</li>
		</ul>
	</details>

