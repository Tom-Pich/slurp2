<p>Dans cette page, vous trouverez des liens vers des fichiers <i>markdown</i> conçus pour fournir du contexte clair à l’IA.</p>

<h2>Soignez votre prompt</h2>

<p>Il est hors de mon propos ici de vous apprendre à bien vous servir de l’IA, mais voici tout de même quelques grandes lignes. Pour en savoir plus, vous pouvez aller voir la <a href="https://www.pichegru.net/divers/comment-utiliser-l-ia-intelligemment#id_auto_14">page</a> traitant du sujet destinée à mes élèves de spécialité NSI 😜.</p>

<ul>
	<li>Indiquez-lui le <b>rôle</b> qu’elle doit jouer.</li>
	<li>Énoncez clairement <b>ce que vous attendez d’elle</b>.</li>
	<li>Fournissez-lui un <b>contexte clair et adapté</b> : format <i><a href="https://docs.forge.apps.education.fr/modeles/tutoriels/tutomd/">markdown</a></i>, ni trop court (sinon ses réponses risquent d’être trop générales ou inadaptées) ni trop long (au risque qu’elle se perde dans le contexte).</li>
	<li>Créez régulièrement une <b>nouvelle conversation</b>. Si une conversation devient trop longue, l’IA s’embrouille dans le contexte.</li>
</ul>

<p>N’oubliez pas, dans votre prompt initial, de précisez le rôle que vous souhaitez lui attribuer :</p>

<p class="border p-½ bg-grey-900">
	Agis en tant qu’assistant MJ pour le système SLURP.<br>
	Voici le contexte : [Fichiers et autre contexte entré à la main].<br>
	Ma demande : [...]
</p>

