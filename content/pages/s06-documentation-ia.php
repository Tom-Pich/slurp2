<h2>Exemples d’utilisation</h2>

<p>De manière générale, fournissez toujours à l’IA le fichier <i>Présentation de SLURP</i>.</p>
<ul>
	<li>soit le fichier lui-même par un clic droit &gt; enregistrer la cible du lien sous…,</li>
	<li>soit un cliquant sur le lien et en faisant un copier-coller de son contenu</li>
</ul>

<p>Vous voulez que l’<b>IA vous aide à élaborer votre personnage</b>, en vous proposant des Avantages, des Désavantages et des compétences appropriés ? Décrivez-lui le profil de personnage et donnez-lui les fichiers, <i>Création d’un personnage</i>, <i>Listes des avantages et désavantages</i> et <i>Listes des compétences</i> et laissez-vous guider.</p>

<p>Vous voulez que l’<b>IA vous assiste dans la création de votre scénario</b> en tenant compte des éléments des PJ ? Donnez-lui le fichier <i>Présentation de SLURP</i> ainsi qu’une fiche simplifiée des PJ.</p>

<p>Vous voulez savoir comment votre <b>PNJ mage pourrait exploiter ses sorts</b> pour que les PJ en bavent ? Donnez-lui le fichier <i>Magie</i> et <i>Liste des sorts</i>.</p>