<section>
	<h2>Les repas quotidiens</h2>

	<p>Le rythme des journées est dicté par la lumière du soleil, le travail et, de manière très importante, par les prescriptions de l’Église.</p>

	<p>Le modèle de base est de deux repas par jour : le <b>disner</b> (en fin de matinée) et le <b>souper</b> (en fin de journée). Manger plus souvent, notamment tôt le matin, était souvent associé au péché de gourmandise ou à un manque de contrôle de soi.</p>

	<!-- Classe populaire -->
	<details>
		<summary>
			<h3>Pour la classe populaire (paysans, ouvriers, artisans)</h3>
		</summary>
		<p>Pour ceux qui pratiquent un travail physique exigeant, la règle théorique des deux repas est impossible à tenir. Une tolérance est donc admise.</p>

		<p><b>L’aube (5h - 6h) : le déjeuner</b> (officieux) pour les travailleurs de force, les enfants, les vieillards. C’est une collation rapide prise sur le pouce avant de partir aux champs ou à l’atelier : un morceau de pain noir ou de seigle, un peu de fromage de garde, parfois frotté d’ail pour donner de la force, le tout arrosé d’un coup de piquette ou de cervoise tiède.</p>

		<p><b>Fin de matinée (10h - 11h) : le disner.</b> Premier vrai repas. Aux champs, consommé froid (pain, oignon, lard salé, fromage). À la maison ou à l’atelier, on peut manger un reste de brouet réchauffé.</p>

		<p><b>Milieu d’après-midi (en été) : La méridienne.</b> Lors des longues journées de moisson en été, les paysans s’accordent une pause pour dormir un peu à l’ombre et manger un morceau de pain avec des fruits ou du fromage.</p>

		<p><b>Le coucher du soleil (18h - 19h) : le souper.</b> C’est le repas principal et le seul chaud de la journée. Son nom vient de la « soupe », une tranche de pain que l’on arrose avec le potage (un bouillon de légumes de saison et de légumineuses qui a mijoté toute la journée dans la marmite). C’est un moment familial autour de l’âtre.</p>
	</details>

	<!-- Nobles et bourgoisie -->
	<details>
		<summary>
			<h3>Pour la noblesse et la riche bourgeoisie</h3>
		</summary>

		<p>Chez les élites, le respect des préceptes religieux et de l’étiquette est essentiel. On ne mange pas avant d’avoir entendu la messe du matin. Prendre de la nourriture dès le réveil est jugé indigne d’un homme de qualité. La matinée est consacrée aux affaires, à la chasse ou à la prière, le ventre vide.</p>

		<p><b>Fin de matinée (10h - 11h) : Le disner.</b> C’est le repas le plus important de la journée pour la sociabilité. Il se compose de plusieurs services. On y sert des viandes rôties, des poissons selon le calendrier, des tourtes et des sauces épicées.</p>

		<p><b>Fin d’après-midi (17h - 18h) : le souper.</b> Plus léger que le disner (en théorie), il se déroule avant la tombée de la nuit pour économiser les chandelle. On y mange des potages clairs, des gelées de viande ou de poisson, et des entremets sucrés.</p>

		<p><b>Le coucher : le boutehors.</b> Juste avant de dormir, dans la chambre à coucher, on sert une dernière collation aux seigneurs et à leurs invités de marque. On y boit du vin épicé (hypocras) ou du claret, accompagné d’« oublies » (gaufres légères) et d’épices de chambre (graines de coriandre ou d’anis enrobées de sucre). Cela est censé faciliter la digestion et purifier l’haleine avant le sommeil.</p>
	</details>

