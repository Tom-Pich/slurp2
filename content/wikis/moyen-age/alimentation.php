<section>

	<h2>La cuisine médiévale</h2>

	<p>La cuisine du quotidien est une cuisine du <b>bouilli</b>, simple et monotone. La cuisine du rôti (viandes à la broche), du frit (beignets) et des saveurs complexes (sauces aux épices exotiques) est un marqueur de richesse réservé aux jours de fête ou aux tables seigneuriales.</p>

	<!-- Pain et bouillies de céréales -->
	<details>
		<summary>
			<h3>Pain &amp; bouillies de céréales</h3>
		</summary>
		<p>L’immense majorité des calories quotidiennes provient des céréales. Le <b>pain</b> (noir ou bis pour le peuple, blanc pour les aisés) est la base de chaque repas. Pour les plus pauvres, il est souvent remplacé par la <b>bouillie</b> (d’avoine, d’orge ou de millet), plus économique car elle ne nécessite ni mouture fine au moulin banal, ni four.</p>
		<p>Avant le pain, la <b>bouillie</b> (souvent appelée gruau ou bren) est l’aliment le plus consommé par le peuple, de la petite enfance à la vieillesse. Elle demande simplement de concasser grossièrement les grains et de les faire bouillir dans un pot de terre sur l’âtre de la maison.</p>
	</details>

	<!-- Potages et brouets -->
	<details>
		<summary>
			<h3>Potages &amp; Brouets</h3>
		</summary>
		<p>Le repas chaud de tous les jours est presque toujours un plat unique cuit à l’eau dans une marmite suspendue sur l’âtre. Ce <b>potage</b> (dont la version la plus courante est la porée) est un bouillon épais de légumes de saison (poireaux, choux, navets) et de légumineuses (fèves, pois) qui mijote de longues heures.</p>
		
		<p>Au Moyen Âge, le mot « soupe » désigne d’abord la tranche de pain sur laquelle on verse un bouillon. Le plat en lui-même s’appelle potage ou brouet.</p>
		
		<p>La <b>porée</b> est le potage quotidien par excellence, consommé par toutes les classes sociales. Il s’agit d’une soupe épaisse de légumes verts (feuilles de poireaux, bettes, choux, épinards) broyés avec du lard salé.</p>
		
		<p>Le <b>brouet</b> est une préparation de viande ou de poisson présentée dans un bouillon lié (épaissi à la mie de pain ou à l’amande) et parfumé d’épices ou d’herbes.</p>
	</details>
	
	<!-- Compagnage -->
	<details>
		<summary>
			<h3>Compagnage</h3>
		</summary>
		
		<p>Pour donner du goût au pain et au potage, on y ajoute ce qu’on appelle le compagnage. Pour le peuple, il s’agit d’un morceau de lard salé, d’un oignon cru, de fromage de garde ou, les jours maigres, d’un hareng salé ou séché.</p>
	</details>
	
	<!-- Viandes et poissons -->
	<details>
		<summary>
			<h3>Viandes &amp; poissons</h3>
		</summary>
		<ul>
			<li><b>Ragoûts et mijotés</b> : viande rissolée ou pochée, puis mijotée dans une sauce (vin, oignons, liée au pain grillé et au sang) ou avec des légumes. Exemples : <em>civets</em>, <em>hochepot</em>…</li>
			<li><b>Fricassées</b> : viande ou poisson saisie à la poêle, puis mijotés avec des herbes, du verjus ou du bouillon. Les petits poissons de rivière (goujons, ablettes) ou les morceaux de hareng sont couramment passés dans la farine avant d’être frits.</li>
			<li><b>Rôti</b> : cuisine seigneuriale, nécessite beaucoup de combustible (bois de qualité), des pièces de viande fraîches et tendres, et une main-d’œuvre dédiée</li>
		</ul>
	</details>

	<!-- Pâtés et tourtes -->
	<details>
		<summary>
			<h3>Pâtés &amp; tourtes</h3>
		</summary>
		<p>La pâte sert de récipient de cuisson et de moyen de conservation. La croûte des grands pâtés, très épaisse et dure, n’est d’ailleurs pas toujours mangée par les nobles, qui la laissent aux serviteurs ou aux pauvres.</p>
	</details>

	<!-- Beignets -->
	<details>
		<summary>
			<h3>Beignets</h3>
		</summary>
		<p>Les beignets sont omniprésents au Moyen Âge. Ils ne sont pas seulement des douceurs de fête, mais aussi une manière courante d’accommoder les restes, les légumes ou le fromage.</p>
		<p>La pâte est faite de farine, d’œufs, de bière, de vin ou d’eau. On la veut assez épaisse pour enrober les ingrédients.</p>
		<ul>
			<li>Les beignets de fromage : Des morceaux de fromage vieux ou frais enrobés de pâte et frits.</li>
			<li>Les beignets d’herbes : On y intègre de la sauge, du persil ou de la menthe hachée.</li>
			<li>Les beignets de fruits : Des tranches de pommes, de poires ou des figues sèches trempées dans la pâte.</li>
			<li>Les beignets de fleurs : Très poétiques, comme les grappes de fleurs de sureau ou d’acacia trempées entières dans la pâte et frites.</li>
		</ul>
		<p>Les beignets sucrés, une fois cuits, sont saupoudrés de sucre (pour les riches) ou de miel chaud.</p>
	</details>
	
	<!-- Cuissons particulières -->
	<details>
		<summary>
			<h3>Quelques cuissons particulières</h3>
		</summary>
		<p><b>Sous la cendre :</b> on enveloppe les aliments (oignons, œufs, racines, ou petits gibiers) dans des feuilles de chou ou de la glaise humide, puis on les enfouit directement sous les braises et la cendre chaude du foyer.</p>
		<p><b>À l’étouffée :</b> les aliments sont placés dans un pot en terre cuite hermétiquement scellé avec un luter (un joint fait de pâte de farine et d’eau) posé au coin du feu. La cuisson se fait lentement dans le propre jus des ingrédients.</p>
		<p><b>Les fers à gaufres :</b> deux plaques de fer gravées, reliées par des pinces à longs manches, que l’on place directement au cœur des braises. On y cuit des pâtes liquides à base de farine, d’eau ou de lait, d’œufs et parfois de fromage. Les oublies sont des gaufres très fines et roulées en cylindre, vendues par les oublieurs dans les rues des villes.</p>
	</details>

	<!-- Boissons -->
	<details>
		<summary>
			<h3>Les boissons</h3>
		</summary>
		<p>L’eau claire étant considérée par la médecine de l’époque comme peu nutritive pour les travailleurs (et parfois difficile d’accès sous forme potable en ville), on boit quotidiennement du vin (généralement jeune et coupé d’eau), de la cervoise (bière sans houblon) ou du cidre, selon les régions de production.</p>
	</details>
</section>

