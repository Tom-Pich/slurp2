			<h3>Les chambres</h3>
		</summary>

		<p>Les aventuriers les plus modestes préfèreront probablement se passer de la discrétion et de la tranquillité d’une chambre pour opter pour la <b>salle commune</b>. Dans ce cas, bien qu’économisant de l’argent, ils devront attendre que les derniers ivrognes aient roulés sous la table avant de dormir. Il est rare que l’aubergiste prenne la peine de pousser les tables pour laisser de la place aux dormeurs. Lorsque la salle commune est déjà encombrée de dormeurs, l’aubergiste permet parfois aux voyageurs d’utiliser une grange ou même l’écurie. </p>

		<p>Les chambres sont nettement plus plaisantes. Surtout si l’aubergiste a la gentillesse ou le sens du commerce suffisant pour déposer une bouillotte sous les couvertures avant l’arrivée des aventuriers !</p>
			
		<p>Dans les <b>chambres simples</b>, le lit n’est souvent qu’une simple paillasse – généralement assez propre – et une couverture en laine épaisse et grossière permet de se protéger du froid. Les voyageurs peuvent occuper de grandes chambres à plusieurs. Rien n’égale toutefois le plaisir de disposer d’une pièce pour une personne, même si cela n’empêche pas toujours d’être dérangé par un voisin ronfleur. Car les murs des auberges, souvent rajoutés par la suite à ces anciennes fermes ne sont pas très épais. </p>

		<p>Dans les <b>chambres luxueuses</b>, le lit dispose d’un véritable matelas et parfois même d’un édredon et d’un oreiller rempli de plumes d’oie ou de duvet.</p>
		
		<p>On ne trouve quasiment jamais de serrures aux portes, beaucoup trop chères et gênantes à entretenir. On préfère en général le <b>loquet</b>, ou alors rien du tout : une simple <b>clenche</b> est la seule protection que l’on peut espérer dans les auberges rurales.</p>

		<p>Un plus du lit, l’hôte dispose d’une <b>table</b> ou d’un <b>coffre </b>où poser ses affaires, d’<b>un peu d’eau</b> (seau ou broc + bassine), d’un <b>vase d’aisance</b> et d’une <b>chandelle</b>.</p>
