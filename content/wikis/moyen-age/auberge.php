<!-- Concevoir une auberge -->
<section>
	<h2>Concevoir une auberge</h2>

	<!-- Questions à se poser -->
	<details>
		<summary>
			<h3>Bonnes questions</h3>
		</summary>
		<ul>
			<li>Quelle est sa taille ?</li>
			<li>Est‑elle luxueuse, normale, très simple, mal famée, sordide ?</li>
			<li>A-t‑elle des particularités ?</li>
			<li>Est‑elle un havre de paix, un lieu animé, une mine à événements ?</li>
			<li>L’aubergiste est‑il quelqu’un de négligeable ou d’important ?</li>
		</ul>
	</details>

	<!-- L’auberge classique -->
	<details>
		<summary>
			<h3>L’auberge classique</h3>
		</summary>

		<p><b>Une salle principale </b>où voyageurs, bourgeois affairés, fermiers et ivrognes échangent nouvelles, rumeurs et défis, noyés dans la fumée de l’énorme cheminée.</p>

		<p><b>Un étage comprenant les appartements de l’aubergiste ainsi que quelques chambres</b> au confort sommaire : une housse de lin bourrée de paille fraîche, de la lumière, une table et un siège en bois.</p>

		<p><b>Un grenier</b> pour entreposer le mobilier inutilisé.</p>

		<p><b>Une cave</b> bien remplie.</p>

		<p><b>Une petite écurie</b> où la mule du propriétaire côtoie les montures de voyageurs.</p>

		<p><b>Un aubergiste</b>, petite célébrité locale, aidé de son équipe</p>
	</details>

	<!-- La grande auberge -->
	<details>
		<summary>
			<h3>La grande auberge</h3>
		</summary>
		<p><b>Salle principale.</b> C’est parfois la seule et unique pièce, en tous cas la plus belle. Le plafond est soutenu par d’épais madriers sculptés.</p>

		<p><b>Salles secondaires.</b> Uniquement si l’auberge est ancienne, ou spécialement destinée à des groupes disparates.</p>

		<p><b>Alcôves.</b> Isolés dans des boxes clos par des cloisons de chêne et des tentures, ou dans des petites pièces sans fenêtre, ceux qui cherchent l’intimité ou le secret apprécient aussi de voir sans être vus.</p>

		<p><b>Comptoir.</b> Cet élément n’est pas obligatoire. Le tavernier navigue alors des tables aux tonneaux ou à la cuisine.</p>

		<p><b>Buffets ou vaisseliers.</b> Les couverts sont souvent exposés sur des rayons dans la pièce principale (effet décoratif et signe de richesse de l’auberge).</p>

		<p><b>Tables et chaises.</b> Selon la clientèle, de petites table rondes, ou le plus souvent de longues tables pour dix ou douze convives.</p>

		<p><b>Estrade.</b> Pour les spectacles ou pour danser.</p>

		<p><b>Terrasse, pergola.</b> Une terrasse dominant la ville, une pergola (terrasse avec une tonnelle de vigne ou de bougainvillées) sont autant d’arguments pour attirer les clients.</p>

		<p><b>Tonneaux.</b> Deux à dix petits tonneaux pour les vins, le cidre et la bière. Plus un ou deux foudres (grands tonneaux ovales de 3 m de haut) dans les grandes hostelleries. Ils sont en général à la cave, sauf dans les petites auberges où l’aubergiste solitaire préfère les avoir à portée de la main.</p>

		<p><b>Cave.</b> On y met les tonneaux, les fromages, certains fruits et légumes, parfois le bois s’il n’y a pas d’appentis.</p>

		<p><b>Cellier ou appentis.</b> Annexe de la cave, mais au niveau du sol : on y met les outils, les réserves de vivres qui craignent l’humidité (grain, jambons...), le bois.</p>

		<p><b>Cheminée.</b> Pour chauffer autant que pour la cuisine.</p>

		<p><b>Basse-cour.</b> Même s’il s’approvisionne au marché, le propriétaire élève des volailles et lapins pour parer à une arrivée impromptue de voyageurs affamés (même en ville). II peut y avoir aussi une porcherie.</p>

		<p><b>Puits.</b> Pour laver autant que pour la boisson, l’auberge a son propre puits d’eau potable, souvent accoté à la demeure, ou même à l’intérieur (plus rare, car il inspire une certaine crainte).</p>

		<p><b>Chambres.</b> Les chambres individuelles sont un luxe. On y trouve un lit, une armoire ou un coffre, un broc avec une cuvette, un vase de nuit.</p>

		<p><b>Paillasses.</b> Dans une rafle commune séparée en boxes par des demi cloisons, façon écurie, des bat flanc couverts de paille ou d’une couverture constituent la couche des clients peu fortunés.</p>

		<p><b>Dortoir.</b> Dans un grenier ou une grange, le sol est jonché de paille, et chacun s’en arrange comme il peut. C’est le lot des vagabonds, des voyageurs fauchés.</p>

		<p><b>Écurie.</b> Elle abrite la monture de l’aubergiste (souvent une mule ou un cheval de trait) et une charrette, et les chevaux des voyageurs. Si l’auberge est importante, un palefrenier s’en occupe et dort dans la réserve de foin au dessus des animaux. Si c’est un relais de malle poste, on est sûr d’y trouver un maréchal ferrant.</p>

		<p><b>Chapelle.</b> Sur les chemins de pèlerinage, une bonne auberge peut disposer d’une petite salle faisant office de chapelle.</p>
	</details>

	<!-- Retour aux origines -->
	<details>
		<summary>
			<h3>Retour aux origines</h3>
		</summary>

		<p>Pour donner du cachet à une auberge, deux solutions : soit imaginer qu’elle est très ancienne, et qu’avec les rajouts effectués au cours des générations c’est devenu un véritable dédale de couloirs, de cours intérieures, d’escaliers, de salles à l’usage oublié (voire de passages secrets, ou simplement murés) ; soit décider qu’elle s’est installée dans un bâtiment ayant à l’origine d’autres fonctions.</p>

		<p><b>Une abbaye ou un prieuré</b>, avec sa promenade abritée sous les voûtes de pierre entourant un jardin intérieur, peut attirer les nobles amateurs de belles pierres, et son immense réfectoire, agrémenté de tentures et de tapisseries, sera le palais préféré d’officiers fortunés. Les cellules y font des chambres austères mais claires, et les anciens bureaux, souvent lambrissés, des suites princières pour hôtes de marque. Quant aux caves et cryptes elles peuvent servir à tant d’usages ! Sans oublier l’utilité, pour les rendez-vous galants ou illicites, des anciens souterrains débouchant en des endroits surprenants.</p>

		<p><b>Une ancienne ferme</b> possède souvent un mur d’enceinte et une porte, des murs extérieurs aveugles, pour limiter les incursions des pillards. Ses grands celliers sont autant de salles où des groupes peuvent s’isoler. Les étables sont transformées en écuries, dont le grenier tapissé de paille, à défaut d’être confortable, est chauffé en hiver par les bêtes du dessous. En été, on peut déjeuner en toute tranquillité aux tables installées dans la cour, autour du puits.</p>

		<p><b>Des moulins.</b> Tout en hauteur, un moulin à vent sera divisé par étage : salle principale en bas, chambres des hôtes au dessus, pièce des hôteliers tout en haut. Un moulin à eau attirera des clients grâce aux charmes de son cadre : cours d’eau, saules, truite au cresson…</p>

		<p><b>Un grenier à grain</b>, vaste bâtiment sans murs intérieurs, peut être aménagé selon la fantaisie de l’aubergiste. Par exemple, les chambres du premier étage peuvent donner sur une mezzanine avec rambarde, qui elle même domine la salle principale où l’on accède par un escalier.</p>
	</details>

	<!-- L’aubergiste -->
	<details>
		<summary>
			<h3>L’aubergiste…</h3>
		</summary>

		<p>
			Une auberge, c’est avant tout son aubergiste, ses manies, ses secrets, son âme. Le patron (ou la patronne) compte pour moitié au moins dans le souvenir que votre auberge va laisser aux visiteurs. Installé depuis un temps certain, il est intimement mêlé à la vie locale : les buveurs de la région le considèrent un peu comme un oncle, tantôt serviable, tantôt bourru. Et les autorités ou groupes influents tentent plus ou moins activement d’en faire un agent de renseignements.<br>
			Quant à l’homme lui même, il peut être :
		</p>

		<ul class="flow">
			<li>
				<b>Acquis aux autorités.</b><br>
				Par lâcheté : il appelle la garde au moindre trouble.<br>
				Par dette : ayant commis un acte répréhensible « couvert » par un potentat local, il doit en retour lui signaler tout signe suspect, espionner pour lui, même contre ses propres sympathies.<br>
				Par conviction : fidèle partisan du régime en place (il a pu participer à son installation), il en est l’oreille et le serviteur fidèle et actif.<br>
				Par intérêt financier : aidé lors de son installation par un banquier, ou ayant pour clientèle principale les membres d’une guilde influente, il veillera à protéger leurs intérêts.
			</li>

			<li><b>Xénophobe.</b> Il éprouve du mépris ou une haine féroce vis à vis de tout ce qui est étranger ou d’une catégorie d’individus : telle race, ou les rouquins, ou les habitants du comté voisin. Ses raisons ? Instinctives, un souvenir personnel (massacre, humiliation), l’intox de ses clients.</li>

			<li><b>Ouvert.</b> Accueillant, curieux, liant, instruit, il s’intéresse aux gens et aux histoires de lieux lointains. Par philosophie, parce que sa constitution ou sa famille l’empêche de partir lui même à l’aventure, parce que c’est un aventurier à la retraite (ex voyageur, marin, caravanier).</li>

			<li><b>Soigneux.</b> Son auberge est claire, agréable, bien tenue. Il est fiable, peut conserver un objet s’il fait confiance à son propriétaire.</li>

			<li><b>Négligeant.</b> L’auberge est sale, infestée de vermine, les murs s’effritent, les portes grincent ou sont branlantes, la toiture fuit, la nourriture est douteuse, parfois absente, il a des dettes qui pourraient lui valoir un incendie « accidentel » alors que les PJ sont présents.</li>

			<li><b>Raffiné.</b> Qu’elle soit simple ou très décorée, l’auberge est connue à des lieues à la ronde, c’est le rendez vous de personnes de goût. La cuisine y est appréciée, mais sa réputation vient aussi de petits détails : chambres fleuries, accessoires de barbier à disposition, petite salle avec fauteuils pour les discussions d’affaires, salon pour partager un verre de liqueur, boudoir pour les dames, musiciens…</li>

			<li><b>Commerçant.</b> Tout lui est bon pour s’enrichir au passage, y compris vendre des informations, vraies ou fausses, ou en acheter, dénoncer des hors-la-loi, monnayer auxdits hors la loi le plan du souterrain pour s’échapper, vendre ou acheter du matériel, prendre sa marge sur les transactions qui se font chez lui, louer ses services ou ceux de son personnel, faire l’intermédiaire avec des individus ou groupes difficiles à rencontrer (ermite, magicien, autorités, monastère, groupe clandestin).</li>
		</ul>
	</details>

	<!-- son équipe -->
	<details>
		<summary>
			<h3>… et son équipe</h3>
		</summary>

		<p>Il est rare que l’aubergiste soit seul. Même célibataire, il trouvera bien un gamin qui, contre gîte (dans un coin d’étable) et couvert (les restes), accomplira les tâches ingrates (nettoyage, vaisselle, service s’il n’est pas trop maladroit). Dans les auberges un peu plus cossues, l’équipe est constituée du couple d’aubergistes, aidé de leurs enfants et/ou de personnel parfois stable, parfois recruté pour de courtes périodes. Une cohabitation qui peut prendre divers visages :</p>

		<ul class="flow">
			<li><b>L’équipe est soudée</b>, tant dans le travail que contre les intrus. Même les aides extérieurs finissent par être considérés comme des membres de la famille.</li>

			<li><b>La famille est privilégiée</b>, les serviteurs traités comme des chiens. L’ambiance est mauvaise, les aides se cachent au moindre pépin, les enfants des aubergistes s’amusent à les maltraiter ou les humilier.</li>

			<li><b>L’aubergiste règne en tyran</b> sur sa femme, ses enfant et le personnel. Ceux-ci sont alors unis pour tirer au flanc, plutôt sympathiques avec les étrangers, mais font aussi du lèche-botte pour calmer le maître de céans. Un fils un peu rebelle peut profiter de la présence d’aventuriers compatissants pour faire un coup d’État dans la maison !</li>

			<li><b>La chaîne familiale.</b> En ville surtout, plusieurs auberges peuvent appartenir à une même famille. Le personnel de l’un va alors aider l’autre pour faire face à une affluence subite, ou tout autre problème.</li>

			<li><b>L’aubergiste solitaire.</b> Sa servante est probablement sa maîtresse, et quelques habitués prêteront main forte en cas d’incident.</li>

			<li><b>Le personnel occasionnel</b> peut être constitué de : paysan saisonnier désœuvré, voyageur désargenté ou qui attend un rendez-vous une saison de plus que prévu, pèlerin, homme à tout faire du bourg qui remplace un serveur malade, ancien compagnon du propriétaire.</li>

			<li><b>Les membres de la famille</b> de l’aubergiste, en dehors de leur lien de parenté et de leur rôle, peuvent être ou avoir été : bûcheron, chasseur, cuisinier, soldat en permission ou démobilisé, cavalier (messager/estafette), rebouteux, herboriste, écrivain public, palefrenier, maréchal ferrant, jongleur, conteur, jardinier, charpentier…</li>
		</ul>
	</details>

