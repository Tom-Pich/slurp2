<!-- Décrire une auberge -->
<section>
	<h2>Décrire une auberge</h2>

	<!-- La lumière -->
	<details>
		<summary>
			<h3>La lumière</h3>
		</summary>
		<p>La première chose qu’on peut observer, c’est la différence nette de luminosité entre la salle et l’extérieur.</p>

		<p><b>En journée</b>, il fera certainement plus sombre dans la pièce : les fenêtres sont souvent réduites au minimum. Dans certaines régions, même, les fenêtres sont inexistantes, et remplacées par des ouvertures que l’on ferme à l’aide d’un volet en cas d’intempéries ou de grand froid. Même si l’aubergiste a hérité d’une auberge vitrée, il ne s’agit au mieux que d’un verre de mauvaise qualité.</p>

		<p><b>De nuit</b>, on est avant tout frappé par le mode d’éclairage : parfois des braseros brûlent à des endroits stratégiques, diffusant une lueur rougeâtre qui laisse de grandes zones d’ombre et dégage une fumée poisseuse qui finira tôt ou tard par noircir entièrement le plafond, obscurcissant encore un peu l’ambiance. Dans d’autres auberges (surtout celles en pierre), des torchères éclairent un peu mieux, mais laissent également leurs traces carbonées sur les murs. Si l’aubergiste désire prendre soin de ses clients autant que de son bâtiment, des lanternes sont plus indiquées, mais aussi plus coûteuses. Une autre alternative étant de disposer des bougies, soit sur chaque table dans les auberges modestes, soit sur des chandeliers et des bougeoirs luxueux dans les établissements plus riches.</p>
	</details>

	<!-- La salle -->
	<details>
		<summary>
			<h3>La salle</h3>
		</summary>

		<p><b>Le plafond</b> est généralement assez bas, et soutenu par des piliers de bois qui divisent le champ de vision des visiteurs. Dans d’autres auberges plus rurales, des poutres soutiennent un toit de chaume ou d’ardoise, et il n’est pas rare de découvrir perché sur l’une de ces poutres un oiseau égaré, ou un chat en maraude.</p>

		<p><b>Le sol</b> n’est que rarement aménagé, tout au plus aura-t-on pris soin de le recouvrir de sciure ou de paille. Généralement, on trouve en dessous, un simple sol en terre battue, tassé par les allers et venues des visiteurs. Dans les auberges de meilleure fréquentation, on a pris soin de disposer des planches de bois en parquet plus ou moins grossier. Encore plus rare, et réservée aux lieux luxueux, des dalles de pierre assemblées donnent une meilleure assise au mobilier, et dans les grandes villes, on pousse parfois jusqu’à assembler de petits morceaux de pierre en mosaïques.</p>

		<p>Enfin, <b>les murs</b> sont généralement nus, encore qu’il ne soit pas rare d’y trouver l’un ou l’autre trophée de chasse dans les auberges rurales. Des draperies ou des rideaux de toile grossière peuvent être accrochés aux parois, mais rarement devant les fenêtres. Il s’agit généralement d’une façon de séparer plusieurs pièces (comme la cuisine), mais il faut faire attention aux odeurs de toutes sortes qui peuvent s’accrocher dans les tissus. La toile est remplacée par un lourd velours dans les plus riches restaurants…</p>
	</details>

	<!-- L’odeur -->
	<details>
		<summary>
			<h3>L’odeur</h3>
		</summary>

		<p>Lorsque la sciure du sol est trempée de vin, c’est une odeur de <b>vinaigre</b> qui finit toujours par apparaître, mélangée avec l’odeur de <b>suif</b> des moyens d’éclairage.</p>

		<p>On trouve également certaines bonnes odeurs au moment des repas, qu’ils proviennent de la broche qui permet de faire cuire les <b>viandes</b> dans la cheminée ou de la porte entrebâillée d’une cuisine. Les odeurs de <b>pâtisseries</b> sont bien plus rare, mais au matin, on peut sentir le délicieux parfum du <b>pain</b> que l’on vient de cuire.</p>

		<p>Si l’aubergiste a <b>un chien ou un chat</b>, soudainement le spectre des odeurs s’élargit vers l’inavouable.</p>

		<p>Heureusement, il y a des moyens de cacher les odeurs indésirables, en particulier dans les auberges de haut niveau : des bouquets de <b>lavande</b> et autres <b>herbes aromatiques</b> hardiment disposés font souvent l’affaire. Des <b>fleurs</b> se conservent moins bien, mais assurent à coup sûr un parfum agréable.</p>
	</details>

	<!-- Le mobilier -->
	<details>
		<summary>
			<h3>Le mobilier</h3>
		</summary>

		<p>Dans les <b>auberges de basse extraction</b>, les tables sont de simples planches posées sur des billots ou des tréteaux, ou au contraire ce sont des tables massives, grandes et lourdes. Des tabourets sommaires ou des bancs sont souvent préférés aux chaises.</p>

		<p>Dans les <b>auberges riches</b>, les tables sont assemblées avec le plus grand soin pour donner l’impression d’être taillées d’une seule pièce, et nettoyées avec soin. Elles sont souvent recouvertes d’un vernis pour en adoucir la surface. Les chaises sont parfois remplacées par des fauteuils, mais dans la plupart des cas, on trouve un mélange des deux.</p>

		<p>Les tables perdent généralement en taille ce qu’elles gagnent en qualité : dans les auberges populaires, on trouve <b>deux ou trois grandes tables</b> où les convives se partagent la place sans se connaître (ce qui est d’ailleurs une bonne façon de rencontrer de nouvelles personnes), dans les auberges plus luxueuses, la discrétion est plus importante et les <b>tables dépassent rarement 4 places</b>.</p>

		<p>Il est possible de trouver un <b>buffet sur lequel est rangée la vaisselle</b>. Les habitués apportent parfois leur chope et couvert s’ils n’ont pas confiance dans la propreté du lieu. Dans les bouges, il est possible de tremper une chope sale dans le tonneau d’eau à disposition des clients. </p>

		<p>Il est <b>très rare de trouver un comptoir</b> dans une auberge. C’est une pratique qui commence seulement à apparaître dans les villes, et plus particulièrement dans les tavernes. Les <b>tonneaux</b> de bière et de vin sont souvent posés dans un coin de la pièce, sous la surveillance de l’aubergiste.</p>

	</details>

	<!-- La clientèle -->
	<details>
		<summary>
			<h3>La clientèle</h3>
		</summary>

		<p>Le bruit ne vient qu’ensuite : la clientèle est rarement silencieuse. Qu’elle soit avachie sur les tables en fin de soirée dans les lieux de basse extraction, ou droite et souriante sur de longues chaises, il est rare qu’elle ne prête pas une <b>attention distraite</b> aux voyageurs qui entrent. Les auberges sont assez rarement bondées, sauf durant un grand festival ou une foire populaire.</p>

		<p>De fait, dans les villages, hormis la clientèle occasionnelle de <b>voyageurs</b>, on n’y trouve la plupart du temps que des <b>paysans</b> qui viennent profiter un peu de la présence des autres.</p>

		<p>Dans les villes, ce sont les <b>habitués</b>, éternels désœuvrés ou grands solitaires qui forment la plus grande partie de la clientèle. L’un souhaite échapper aux humeurs de sa femme, un autre noie son manque de succès dans la bière tandis qu’un troisième quémandera pour la dernière fois – jure-t-il – une avance à l’aubergiste pour disposer encore d’un verre.</p>

		<p><b>Les nobles ne fréquentent pas les auberges.</b> Lorsqu’ils ont des affaires à y traiter, ils préfèrent en général y envoyer leurs chambellans. Quand il s’agit de se loger, ils préfèrent de loin aller habiter chez un cousin plus ou moins proche à qui ils s’empresseront de rappeler les liens de parenté.</p>

		<p>Bien plus souvent, c’est la <b>suite complète d’un marchand</b> qui amène de l’originalité dans l’auberge. Un ou deux serviteurs, un comptable trésorier, un écuyer et quelques gardes du corps se rassemblent alors et prennent possession d’un pan entier de la pièce. Encore une fois, ce type de clientèle ne se mêlera aux autres que si elle a quelque chose à y gagner.</p>
	</details>

	<!-- L’aubergiste -->
	<details>
		<summary>
			<h3>L’aubergiste</h3>
		</summary>

		<p>Il y a autant d’aubergistes qu’il y a d’auberges, et sa personnalité et son caractère sont souvent le reflet de l’ambiance du bâtiment… à moins que ce ne soit le contraire. La plupart du temps, il n’est pas possible de le différencier du reste de la clientèle, si ce n’est par le fait qu’il fasse le <b>premier pas vers les nouveaux arrivants</b>.</p>

		<p>Il porte généralement un <b>tablier de cuir</b> qui sert aussi bien à essuyer les couteaux qu’à se protéger de la saleté. Il faut ajouter à cela que l’aubergiste est <b>la plupart du temps un homme</b> : monter les tonneaux, ranger les tables, mettre parfois à la porte les indésirables, tout cela nécessite souvent une force dont ne disposent que de rares femmes. La corpulence n’est pas toujours de règle, mais un <b>aubergiste gros</b> inspire bien souvent la confiance.</p>

		<p>Ce qui fait réellement tout le charme d’un aubergiste, c’est <b>son histoire</b>, le passé qui l’a conduit à se consacrer à ce métier assez ingrat.</p>

		<p>Passons rapidement sur les ennuyeux, ceux qui ont <b>hérité de l’auberge</b> après le décès de leur père, ceux qui ont été <b>élus par les autres villageois</b> pour ouvrir la taverne du village, officialisant une situation qui perdurait depuis longtemps. Car souvent, <b>l’aubergiste n’est qu’un paysan</b> qui a rajouté une corde à son arc, un viticulteur qui écoule sa marchandise et faisant appel à sa femme pour la cuisine soutenu en cela par la coopérative locale.</p>

		<p>Beaucoup plus intéressant : l’aubergiste contrit, celui qui a <b>vécu par le passé de grandes aventures</b>, qui a été marin, guerrier, explorateur peut-être, et qui, après une grande fièvre, un membre arraché ou tout simplement le temps qui passait a été obligé d’abandonner cette vie trépidante au profit du quotidien calme et rangé de l’auberge. Celui-là a rapidement l’œil qui brille lorsqu’il voit dans les nouveaux arrivants le héros qu’il a lui même été. Et hors de question de laisser partir les voyageurs sans avoir entendu leur histoire, ponctuant les aventures contées de bruyants éclats de voix : « <i>Ha ! Oui : je me souviens bien de cela !</i> ».</p>

		<p>Beaucoup plus rares encore sont les <b>déchus</b>, les nobles qui ont décidé de refaire leur vie au loin après un scandale, un moine exclus pour une faute quelconque et qui continue à servir de la bière contre monnaie trébuchante, cette fois. Ou encore le hors-la-loi qui se terre dans un lointain village, en espérant que ses erreurs passées seront oubliées avec le temps.</p>

		<p>Il y a enfin ceux qui, dans les grandes villes, bénéficient d’une grande <b>formation dans l’art de la table</b>, souvent parce que leur famille ne leur laissa pas le choix. </p>
