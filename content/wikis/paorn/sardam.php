	<h2>Politique &amp; organisation</h2>

	<p>La Sordolia – et donc Sardam – est dirigée par le <b><a href="/wiki/paorn/maison-avrelanche">prince Margor d’Avrelanche</a></b>.</p>

	<!-- La direction politique au château -->
	<details>
		<summary>
			<h3>La direction politique au château</h3>
		</summary>
		<p>Le château de Sardam concentre les fonctions souveraines directes des terres de la couronne : la <b>défense</b>, la <b>diplomatie</b>, la <b>législation</b> et l’<b>administration générale des Territoires</b> de la Couronne. Le Prince Margor d’Avrelanche, pragmatique et militaire de tempérament, assume directement le rôle de connétable et la direction des armées sans intermédiaire. Il s’appuie au quotidien sur son chancelier, Aldric Vasshen. En plus de diriger la chancellerie, ce dernier assume la lourde responsabilité de l’Administration des Territoires, supervisant les baillis, l’exploitation des forêts et la coordination avec les grands vassaux de la province. Cette double charge fait du chancelier l’homme le plus occupé de l’appareil d’État sordolien.</p>
