		<summary>
			<h3>Structure de la ville</h3>
		</summary>

		<p>La ville possède une double enceinte sur son flanc nord, résultat d’une extension progressive. À l’Est et à l’Ouest, les deux parties de la ville fusionnent, l’ancienne muraille ayant été en partie démolie.</p>

		<p>Sardam est accessible par deux portes principales : la porte Sud, dite porte de Lardam, et la porte nord, appelée porte de Solidam. La ville se situe à 220 km au sud de Solidam et à 255 km au nord de Lardam, ces distances étant données par la route.</p>

		<p>Enfin, fait notable, Sardam est équipée d’un système de tout-à-l’égout.</p>
	</details>

