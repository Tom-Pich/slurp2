			<summary>
				<h4>Fiskerley – Hameau de pêcheurs et débarcadère</h4>
			</summary>
			<p>Situé hors les murs au sud-est de la cité, le faubourg de Fiskerley s’étend le long de la Rojen. Ce hameau modeste abrite une population de pêcheurs artisans qui approvisionnent quotidiennement le marché de Sardam en poissons de rivière. Fiskerley est également le point de réception et de traitement du bois : une estacade flottante y arrête les grands trains de bois flotté et le bois de chauffage qui descendent le fleuve depuis les monts Versdvar. Une scierie et un chantier de débitage y débitent les troncs bruts en planches et en bûches de chauffage avant leur acheminement intra-muros par la porte Sud ou par la darse de Deventer.</p>
		</details>

