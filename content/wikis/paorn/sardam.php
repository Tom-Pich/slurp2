				<h4>Nyveg – Quartier nord</h4>
			</summary>
			<p>Situé entre l’ancienne et la nouvelle enceinte nord, Nyveg est un quartier populaire et logistique, né de l’expansion de la ville et des échanges commerciaux avec Solidam. Le quartier s’organise le long d’une large avenue de 200 mètres reliant la porte de Solidam à l’ancienne porte de la ville. C’est sur cet axe que se concentrent les cours de déchargement, les écuries et les entrepôts de transit pour les caravanes marchandes. Afin de préserver l’efficacité défensive de la double enceinte, les règlements de la ville interdisent toute construction contre la muraille extérieure, y maintenant un chemin de ronde dégagé.</p>
