	<!-- Le Palais du Grand Juge -->
	<details>
		<summary>
			<h3>Le Palais Dommers</h3>
		</summary>
		<p>Situé dans le quartier du Pied-du-Roc, à proximité immédiate de la montée du château, le Palais Dommers est un édifice de granit sombre à l’architecture austère et géométrique. C’est là que siège le Grand Juge de Sordolia, assisté de ses deux lieutenants (civil et criminel) et du procureur du Prince. Cette cour supérieure gère la haute justice criminelle de la province, examine les appels des prévôtés rurales et tranche les litiges de contrats ou d’héritages de la noblesse provinciale. En logeant ce tribunal hors les murs du château, le pouvoir princier délègue la magistrature technique tout en maintenant une présence judiciaire visible et solennelle au cœur du quartier des notables.</p>
	</details>

	<!-- La Grande Recette -->
	<details>
		<summary>
			<h3>La Grande Recette et Monnaie de Sordolia</h3>
		</summary>
		<p>Également installé au Pied-du-Roc, ce bâtiment de pierre fortifié et lourdement gardé sert de cœur financier à la province. Dirigée par le Grand Trésorier provincial, Maître Gunter Kross — un obme de robe, légiste de carrière formé à Olméria. C’est à la « Grande Recette » que sont acheminés, comptabilisés et entreposés les impôts, les péages et les redevances seigneuriales collectés par les prévôts dans tout la domaine princier. Ses caves sécurisées abritent le Trésor de la Sordolia ainsi que l’atelier de frappe monétaire impériale et provinciale. C’est également dans ces murs que se réunit la Chambre des Comptes, l’organisme indépendant chargé de l’audit et du contrôle de tous les officiers financiers du territoire sordolien.</p>
	</details>

