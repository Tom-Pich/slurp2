		<!-- La porte Nord -->
		<details>
			<summary>
				<h4>La porte Nord</h4>
			</summary>
			<p>La porte nord de la ville est flanquée de deux grandes tours portant chacune une gravure en haut-relief, représentant un personnage presque aussi haut que la tour.</p>

			<p>La tour de gauche représente <i>Matarcald le Défricheur</i>, ancien roi du Nord et fondateur légendaire de la ville. Un géant de granit sculpté en pied, de face, dans une posture d’autorité immobile. Il tient une hache à deux mains, lame vers le bas. Il ne porte pas d’armure mais une cape épaisse et une couronne simple. Son visage est carré, la barbe taillée en pointe, le regard droit devant lui. Sous ses pieds, une forêt stylisée d’arbres tombés. L’inscription en bas de la tour : <i>Il a offert la terre aux hommes</i> – en sordolien archaïque.</p>

			<p>La tour de droite montre <i>Sendra d’Avrelanche</i>, guerrière et première princesse de Sordolia. Une femme debout, de profil à trois quarts, en armure complète, la main droite levée tenant une épée à la verticale en posture de serment. Ses cheveux sont tressés, visibles sous un heaume ouvert. Son visage est serein, presque froid. Derrière elle, en bas-relief plus discret, un château en construction. L’inscription : <i>Elle a tenu ce que d’autres n’osaient bâtir</i> – en sordolien archaïque.</p>
		</details>

		<!-- La darse de Deventer -->
		<details>
			<summary>
				<h4>La darse de Deventer et la porte d’eau</h4>
			</summary>

			<p>Afin de sécuriser le déchargement des cargaisons de marchandises en provenance du sud de la province, la ville dispose d’un port intérieur fortifié situé dans le quartier de Deventer : la Darse. Ce bassin artificiel de taille modeste (33 mètres de large sur 26 mètres de long), entièrement maçonné en granit, permet d’accueillir et de décharger simultanément trois à quatre gabares de 30 tonnes à l’abri des remparts. En raison de ces dimensions restreintes, les navires y entrent en marche avant et en ressortent obligatoirement en marche arrière, halés depuis les quais ou repoussés à la perche jusqu’au fleuve.</p>

			<p>L’étroitesse du canal d’accès et de la darse interdit l’entrée des grands trains de bois flotté (les assemblages de troncs de 30 à 50 mètres de long descendant la Rojen depuis les monts Versdvar). Ces derniers sont arrêtés et stockés sur le fleuve en amont, puis débités extra-muros à la scierie du hameau de Fiskerley. Seul le bois d’œuvre déjà travaillé (poutres, charpentes, planches) est autorisé à pénétrer dans la darse à bord de barques plates ou par la porte Sud de la ville.</p>

			<p>Les bateaux accèdent à la darse par un canal d’une quinzaine de mètres de large qui franchit l’enceinte Est à travers une porte d’eau (la Wessertur) hautement fortifiée :</p>

			<ul>
				<li><b>L’arche flanquée :</b> la muraille franchit le canal par une arche de pierre surbaissée, encadrée par deux épaisses tours d’artillerie semi-circulaires avancées sur la Rojen. Ces tours permettent d’effectuer des tirs croisés sur tout navire s’approchant du chenal.</li>

				<li><b>La double herse métallique :</b> sous l’arche, le passage est condamné par deux grilles de fer coulissantes indépendantes. Ces herses descendent à travers la maçonnerie jusqu’au lit du canal pour empêcher toute intrusion sous-marine. Elles sont actionnées par des cabestans situés dans la salle de garde supérieure de la porte.</li>

				<!-- <li><b>La chaîne des bateliers :</b> à l’entrée du canal d’accès, une lourde chaîne de fer forgé est tendue en travers de l’eau. Reliée à un treuil logé dans l’une des tours de flanquement, elle est levée et verrouillée chaque soir à la cloche du couvre-feu, interdisant l’approche de la porte d’eau.</li> -->
			</ul>

			<h5>Le système de treuil et de poulies</h5>

			<p>Un astucieux système de treuil et de poulies permet de tracter les gabares et le bois sur les 140 m séparant la fin du chemin de halage après Fiskerley et l’entrée de la Darse en amont.</p>

			<h5>La maintenance hivernale</h5>

			<p>Pendant la période hivernale, lorsque la Rojen et les marais gèlent, les maçonneries et les grilles de la porte d’eau subissent d’importantes contraintes. Le gel des eaux de surface risque de bloquer les herses en position ouverte ou fermée. La garde de Deventer y maintient donc une corvée quotidienne : les auxiliaires du guet doivent briser la glace à la masse autour des herses pour libérer les grilles, tandis que les glissières et les poulies des cabestans sont régulièrement enduites de saindoux pour empêcher le gel des engrenages.</p>
