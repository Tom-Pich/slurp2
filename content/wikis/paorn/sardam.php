			<h3>L’Hôtel du Bailliage</h3>
		</summary>
		<p>Situé dans le quartier du Vieux-Spicher, L’Hôtel du Bailliage (communément appelé <i>Le Bailliage</i>) est le centre névralgique de l’administration civile et de l’ordre public de la cité et de sa région agricole. Le bâtiment abrite les <b>bureaux du Bailli central</b>, responsable de la gestion économique et de la voirie de la clairière de Sardam, <b>ainsi que ceux du Prévôt de la cité</b>, chargé de la police des marchés, du contrôle des corporations d’artisans et de la sécurité intérieure de la ville. Le complexe intègre également le <b>poste central du guet</b> de la ville, placé sous l’autorité du capitaine de la garde urbaine, ainsi que les Geôles de la Prévôté, des cellules de détention temporaires réservées à la criminalité de droit commun et aux délits civils ordinaires, distinctes des cachots militaires du château.</p>
