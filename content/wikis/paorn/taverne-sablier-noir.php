<!-- L’étage -->
<section>
	<h2>L’étage</h2>
	<p>Au dessus du bar, un balcon en bois où se trouvent des clients. On distingue mal combien de personnes y sont installées lorsque l’on pénètre dans les lieux.</p>
	
	<p>C’est sur ce balcon que les jeux d’argent se déroulent. On y accède par l’escalier situé à gauche du bar. Une fois monté, on découvre une pièces rectangulaire de 6x4 mètres environ avec 4 tables de 4 personnes. Il y a une tenture brodée, au fond de la pièce représentant un combat de joutes.</p>
	
	<p>En haut de l’escalier se tient un homme, peu enclin au bavardage, chargé de régler les problèmes pouvant survenir au cours d’une partie. Il faut attendre là avant d’être installé sur la mezzanine ou dans l’une des deux salles situées à l’arrière.</p>
</section>