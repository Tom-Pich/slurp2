<section>
	<p>Elle se situe à l’angle d’une rue très commerçante et passante et d’une ruelle plus étroite où se situent des habitations, dans le quartier de la Croisée. A l’angle, donnant sur la rue principale, une enseigne peinte sur laquelle est dessiné un sablier noir. A l’arrière de la taverne se situe une rue parallèle où se trouve différentes échoppes et ateliers. </p>
	
	<p>Le bâtiment est constitué d’un rez-de-chaussée en pierre de taille avec un étage à colombage. Trois hautes fenêtres à petits carreaux donnent sur la rue principale et à l’arrière sur la rue parallèle. D’une cheminée s’échappe de la fumée. </p>
	
	<p>L’établissement est soumis à une licence et tout joueur doit s’acquitter d’une taxe pour jouer aux jeux d’argent.</p>
</section>

<!-- Histoire -->
<section>
	<h2>Son histoire</h2>
	<p>Plus ancienne taverne de la ville qui était le premier endroit où les voyageurs de passage faisaient étape, lorsque autrefois, elle proposait des chambres désormais transformées en des salles de jeux. La direction est passée de génération en génération depuis lors.</p>
	
	<p>Les voyageurs, marchands, nobles s’y retrouvaient pour faire étape et se détendre après un long voyage notamment pour ceux venant du Nord où les distractions sont rares. C’était donc autour de musiciens que l’ambiance était animée et que les jeux d’argent s’organisaient. Ainsi qu’importait l’origine sociale, tous se mêlaient, le temps d’une soirée. Ce lieu est devenu emblématique de la ville et continue à attirer beaucoup de monde et est notamment réputé pour être un haut lieu pour les joueurs.</p>
</section>

<!-- salle principale -->
<section>
	<h2>La salle principale</h2>
	
	<p>L’ambiance, une fois le seuil franchi est chaleureuse et l’odeur qui s’en dégage invite au repas. Une immense cheminée au fond, à droite de la porte d’entrée illumine la pièce. Des bougies sont disposées sur le linteau. Sur le conduit, une imposante sculpture ronde en étain est accrochée. Elle représente une scène de labour.  La chaleur dégagée par le foyer, les grandes fenêtres en demie lune, les lustres en fer forgé suspendus sur lesquels brûlent des bougies, les coupelles à bougies en étain fixées aux murs, ça et là apportent également une lumière douce tout comme les lanternes posées sur les tables et invitent le visiteur à s’installer. </p>
	
	<p>Un musicien assis, se trouve à gauche de la cheminée et joue du psaltérion. Des clients, assis sur des bancs, de part et d’autre du foyer, consomment autour du foyer et profite de la musique.</p>
	
	<p>La serveuse brune, d’une quarantaine d’année est vêtue d’une longue robe bleue sur laquelle est noué un tablier blanc. Elle porte fichu écru. Elle se presse autour des tables.</p>
	
	<p>Au fond, face à la porte se trouve le bar derrière lequel des fûts sont empilés. De part et d’autre de ces fûts sont disposés, sur des étagères, pots, gobelets, pichets, assiettes. Le patron, un homme d’une quarantaine d’année, rouquin, rougeaud, petit et corpulent, y accueille les clients avec le sourire. Il a l’œil pétillant qui traduit sa bonne humeur mais aussi un sens aiguisé des affaires.</p>
	
	<p>A gauche du bar, une porte, les latrines et un escalier qui mène à la mezzanine située au dessus du bar et aux pièces situées à l’étage.</p>
	<p>A droite du bar, une porte derrière laquelle se trouve la cuisine et le logement du tavernier. On y voit régulièrement un jeune homme mince vêtu d’un tablier entrer et sortir chargé de plateaux contenant des plats.</p>
	
	<p>Il y a une 7 grandes tables où 8 personnes peuvent s’installer sur des bancs.</p>
	
	<p>Certains discutent, d’autres jouent aux échecs et aux dés.</p>

